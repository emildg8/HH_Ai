/**
 * COPILOT-INT: auto prep при bucket E / hhSiteState invited после sync переговоров.
 */

import { loadPreferences } from './preferences.mjs';
import { getVacancyRecord, loadQueue, updateVacancyRecord } from './store.mjs';
import { classifyRecordOutcome } from './outcome-classifier.mjs';
import { buildInterviewPrepPack } from './interview-prep.mjs';
import { HH_SITE_STATES } from './hh-vacancy-response-state.mjs';

/**
 * @param {object} [prefs]
 */
export function isAutoPrepOnInviteEnabled(prefs) {
  const p = prefs || loadPreferences();
  return p?.applyIntelligence?.autoPrepOnInvite !== false;
}

/**
 * @param {object} rec
 */
export function recordEligibleForAutoPrep(rec) {
  if (!rec) return false;
  const st = String(rec.hhApply?.hhSiteState || '');
  const outcome = classifyRecordOutcome(rec);
  const isInvite = st === HH_SITE_STATES.INVITED || st === 'invited' || outcome.bucket === 'E';
  if (!isInvite) return false;
  if (rec.interviewPrep?.autoGeneratedAt) return false;
  return true;
}

/**
 * @param {string[]} updatedIds
 * @param {{ prefs?: object, dryRun?: boolean }} [opts]
 */
export async function autoPrepAfterNegotiationSync(updatedIds = [], opts = {}) {
  const prefs = opts.prefs || loadPreferences();
  if (!isAutoPrepOnInviteEnabled(prefs)) {
    return { skipped: 'disabled', prepared: [], errors: [] };
  }

  const ids = new Set((updatedIds || []).map(String));
  if (!ids.size) return { skipped: 'no_updates', prepared: [], errors: [] };

  /** @type {object[]} */
  const prepared = [];
  /** @type {object[]} */
  const errors = [];

  for (const id of ids) {
    const rec = getVacancyRecord(id);
    if (!rec || !recordEligibleForAutoPrep(rec)) continue;
    if (opts.dryRun) {
      prepared.push({ id: rec.id, title: rec.title, company: rec.company, dryRun: true });
      continue;
    }
    try {
      const pack = await buildInterviewPrepPack(rec);
      pack.autoGeneratedAt = new Date().toISOString();
      pack.source = 'auto-prep-on-invite';
      updateVacancyRecord(rec.id, { interviewPrep: pack });
      prepared.push({
        id: rec.id,
        title: rec.title,
        company: rec.company,
        vacancyId: rec.vacancyId,
        hasLlm: Boolean(pack.llm),
      });
    } catch (e) {
      errors.push({
        id: rec.id,
        error: e instanceof Error ? e.message : String(e),
      });
    }
  }

  return { prepared, errors, skipped: prepared.length ? null : 'no_eligible' };
}

/**
 * Скан всей очереди (fallback после apply-negotiations-cache без diff).
 * @param {{ prefs?: object, dryRun?: boolean }} [opts]
 */
export async function autoPrepScanQueue(opts = {}) {
  const prefs = opts.prefs || loadPreferences();
  if (!isAutoPrepOnInviteEnabled(prefs)) {
    return { skipped: 'disabled', prepared: [], errors: [] };
  }
  const ids = loadQueue().filter(recordEligibleForAutoPrep).map((r) => r.id);
  return autoPrepAfterNegotiationSync(ids, opts);
}
