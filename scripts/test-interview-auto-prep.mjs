/**
 * COPILOT-INT: auto prep on invite + debrief patterns.
 */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  isAutoPrepOnInviteEnabled,
  recordEligibleForAutoPrep,
  autoPrepAfterNegotiationSync,
} from '../lib/interview-auto-prep.mjs';
import { recordDebriefPattern } from '../lib/interview-debrief-patterns.mjs';
import { mergeNegotiationsIntoQueue } from '../lib/hh-negotiations-sync.mjs';
import { closeKnowledgeDb, runMigrations } from '../lib/knowledge-store.mjs';
import { buildCandidateContext, clearContextCache } from '../lib/candidate-context-bundle.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const tmpDb = path.join(os.tmpdir(), `hh-copilot-int-${process.pid}.db`);

try {
  if (fs.existsSync(tmpDb)) fs.unlinkSync(tmpDb);
} catch {
  /* ignore */
}

assert.equal(isAutoPrepOnInviteEnabled({ applyIntelligence: {} }), true);
assert.equal(isAutoPrepOnInviteEnabled({ applyIntelligence: { autoPrepOnInvite: false } }), false);

const invitedRec = {
  id: 'rec-invite-1',
  vacancyId: '999001',
  title: 'DevOps',
  company: 'TestCorp',
  hhApply: { hhSiteState: 'invited', responseSubmitted: true },
};
assert.equal(recordEligibleForAutoPrep(invitedRec), true);
assert.equal(recordEligibleForAutoPrep({ ...invitedRec, interviewPrep: { autoGeneratedAt: '2026-01-01' } }), false);
assert.equal(recordEligibleForAutoPrep({ ...invitedRec, hhApply: { hhSiteState: 'declined' } }), false);

const mergeResult = mergeNegotiationsIntoQueue({ items: [] });
assert.ok(Array.isArray(mergeResult.updatedIds));
assert.equal(mergeResult.updatedIds.length, 0);

const dry = await autoPrepAfterNegotiationSync(['missing-id'], { dryRun: true });
assert.equal(dry.skipped, 'no_eligible');

clearContextCache();
const ctx = await buildCandidateContext({
  title: 'DevOps',
  company: 'Ghost Corp',
  force: true,
  cvText: 'DevOps engineer with Docker and CI/CD experience.',
});
assert.ok(typeof ctx.employerRagBlock === 'string');

runMigrations({ dbPath: tmpDb });
const prefs = { applyIntelligence: { knowledgeStoreEnabled: true } };
const debrief = {
  company: 'TestCorp',
  lastQuestion: 'Расскажите про мониторинг?',
  selfRating: 8,
};
const pat = recordDebriefPattern(debrief, { prefs, storeOpts: { dbPath: tmpDb } });
assert.equal(pat.recorded, true);

console.log('test-interview-auto-prep: OK');
closeKnowledgeDb();
